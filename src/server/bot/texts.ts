const DICTS: Record<Lang, Dict> = { uz, ru, en };

export type TextKey = Key;

export function asLang(l: string | null | undefined): Lang {
  return l === "ru" || l === "en" ? l : "uz";
}

export function bt(lang: string | null | undefined, key: Key, params: Record<string, string | number> = {}): string {
  const s = DICTS[asLang(lang)][key] ?? uz[key];
  return s.replace(/\{(\w+)\}/g, (_m, k) => (params[k] !== undefined ? String(params[k]) : ""));
}

